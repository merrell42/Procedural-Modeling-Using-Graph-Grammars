#include <algorithm>

int min(int a, int b) {
    return std::min(a, b);
}
float min(float a, float b) {
    return std::min(a, b);
}
double min(double a, double b) {
    return std::min(a, b);
}

int max(int a, int b) {
    return std::max(a, b);
}
float max(float a, float b) {
    return std::max(a, b);
}
double max(double a, double b) {
    return std::max(a, b);
}
